#Задание №1. (Базовый уровень)
# Ввод данных
a = int(input("Введите первое целое число: "))
b = int(input("Введите второе целое число: "))

# Вычисления
sum_val = a + b
diff_val = a - b
prod_val = a * b
avg_val = (a + b) / 2

# Вывод результатов
print(f"Сумма: {sum_val}")
print(f"Разность: {diff_val}")
print(f"Произведение: {prod_val}")
print(f"Среднее арифметическое: {avg_val}")
